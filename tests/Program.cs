using System.Numerics;
using Dalamud.Game.ClientState.Conditions;
using Dalamud.Game.ClientState.Objects.SubKinds;
using Dalamud.Game.ClientState.Objects.Types;
using ECommons.DalamudServices;
using PromeRotation;
using PromeRotation.Managers;
using PromeRotation.Spatial.Drawing;
using TargetRangeRing;

const string playerId = "TargetRangeRing_Player";
const string autoId = "TargetRangeRing_Auto";
var manager = Plugin.Instance.DrawManager;
var player = new Player { HitboxRadius = 0.75f };
Svc.Objects.LocalPlayer = player;
var config = new Config();
var drawer = new TargetRingDrawer(config);
int checks = 0;
void Check(bool condition, string message) { if (!condition) throw new Exception(message); checks++; }
drawer.Update();
Check(manager.Items.Count == 1 && manager.Items.ContainsKey(playerId), "Player must render without target or melee job");
var initial = manager.Items[playerId];
Check(initial.Style.FillColor == config.PlayerRingColor && initial.Style.StrokeColor == null && initial.Renderer == RendererType.ImGui, "Player must be an ImGui filled circle");
Check(initial.Geometry.Radius == 0.5f, "Default radius");
int adds = manager.Adds;
for (int i = 0; i < 1000; i++) drawer.Update();
Check(manager.Adds == adds, "Stationary player must not be registered each frame");
player.Position = new Vector3(3, 0, 2); drawer.Update();
Check(manager.Items[playerId].Geometry.Position == player.Position && ReferenceEquals(initial.Style, manager.Items[playerId].Style), "Movement must update geometry and reuse style");
config.PlayerRingSize = 1.2f; config.PlayerRingColor = Vector4.One; drawer.Update();
Check(manager.Items[playerId].Geometry.Radius == 1.2f && manager.Items[playerId].Style.FillColor == Vector4.One, "Player size and color changes");
Svc.PlayerState.ClassJob.RowId = 19; Svc.Targets.Target = new Battle(); drawer.Update();
Check(manager.Items.Count == 3 && Math.Abs(manager.Items[autoId].Geometry.Radius - 4.85f) < 0.0001f, "Target uses actual player hitbox");
Svc.Targets.Target = new Battle { GameObjectId = 2 }; drawer.Update();
Check(manager.Items.ContainsKey(playerId), "Target switch must preserve player");
Svc.Targets.Target = null; drawer.Update();
Check(manager.Items.Count == 1 && manager.Items.ContainsKey(playerId), "Target loss must preserve player");
config.ShowInCombat = true; drawer.Update(); Check(manager.Items.Count == 0, "Combat filter");
Svc.Condition[ConditionFlag.InCombat] = true; drawer.Update(); Check(manager.Items.ContainsKey(playerId), "Combat filter satisfied");
config.ShowInInstance = true; drawer.Update(); Check(manager.Items.Count == 0, "Filters combine with AND");
Svc.Condition[ConditionFlag.BoundByDuty] = true; drawer.Update(); Check(manager.Items.ContainsKey(playerId), "Both filters satisfied");
Svc.Condition[ConditionFlag.InCombat] = false; config.ForceDisplay = true; drawer.Update(); Check(manager.Items.ContainsKey(playerId), "Force display bypasses filters");
config.Enabled = false; drawer.Update(); Check(manager.Items.Count == 0, "Force must not bypass master disable");
config.Enabled = true; config.PlayerRingEnabled = false; drawer.Update(); Check(manager.Items.Count == 0, "Player disable");
config.PlayerRingEnabled = true; drawer.Update();
EventManager.End(); drawer.Update(); Check(manager.Items.ContainsKey(playerId), "Restore after battle cleanup");
Svc.ClientState.Change(); drawer.Update(); Check(manager.Items.ContainsKey(playerId), "Restore after territory cleanup");
Svc.Objects.LocalPlayer = null; drawer.Update(); Check(manager.Items.Count == 0, "Logout removes player");
Svc.Objects.LocalPlayer = player; config.PlayerRingSize = float.NaN; drawer.Update(); Check(manager.Items.Count == 0, "Invalid radius removes player");
config.PlayerRingSize = 0.5f; config.Backend = RenderBackend.VFX; drawer.Update();
Check(manager.Items[playerId].Renderer == RendererType.ImGui, "Player remains ImGui with VFX target backend");
drawer.Dispose(); Check(manager.Items.Count == 0, "Dispose removes player");
drawer.Update(); Check(manager.Items.Count == 0, "Disposed drawer stays inactive");
Console.WriteLine($"PASS: {checks} drawer behavior checks.");
